"""Builds web-app/src/aliv/demo/fixture.ts for the browser preview.

The fields come from the real Rust extractor, so the preview shows what the
desktop app extracts. Regenerate after changing demo/corpus or extract.rs:

  cd src-tauri/plugins/tauri-plugin-aliv-vault
  cargo run -q --example scan --no-default-features -- ../../../../../demo/corpus --json > /tmp/scan.json
  python3 ../../../scripts/aliv-demo-fixture.py /tmp/scan.json
"""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[3]
scan = json.load(open(sys.argv[1]))
docs = []
for row in scan["grid"]:
    d = row["document"]
    path = Path(d["path"])
    docs.append({
        "fileName": d["fileName"],
        "ext": d["ext"],
        "size": d["size"],
        "docType": d["docType"],
        "text": path.read_text(encoding="utf-8"),
        "fields": row["fields"],
    })
out = root / "apps/desktop/web-app/src/aliv/demo/fixture.ts"
body = json.dumps(docs, indent=1, ensure_ascii=False)
out.write_text(
    "// Generated by apps/desktop/scripts/aliv-demo-fixture.py from demo/corpus. Do not edit.\n"
    "import type { Field } from '../types'\n\n"
    "export interface FixtureDoc {\n  fileName: string\n  ext: string\n  size: number\n"
    "  docType: string | null\n  text: string\n  fields: Field[]\n}\n\n"
    f"export const demoDocuments: FixtureDoc[] = {body}\n",
    encoding="utf-8",
)
print(f"wrote {len(docs)} documents to {out}")
